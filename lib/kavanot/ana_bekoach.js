// אות ראשונה של תיבה (מתעלם מניקוד) — לבניית ראשי-התיבות.
function firstLetter(word) {
  for (const ch of word) {
    const c = ch.codePointAt(0);
    if (c >= 0x05d0 && c <= 0x05ea) return ch;
  }
  return '';
}

// קבוצת ראשי-התיבות בת 6 האותיות לכל שורה (למשל אבגיתץ).
export function lineAcronym(line) {
  return line.words.map(firstLetter).join('');
}

// שם המ"ב המלא — 7 קבוצות × 6 אותיות = 42 (אותיות רגילות, נאמן לגזירה).
export const SHEM_MEM_BET = ANA_BEKOACH.map(lineAcronym);

